  <h2>1. Who we are</h2>
  <p>
    Chess Castles is a chess website and app for players in India, free to start, with optional plans. This policy explains what personal data we process,
    why, who can see it, and your rights under India's Digital Personal Data Protection Act, 2023.
  </p>

  <h2>2. What we collect, and why</h2>
  <ul>
    <li><strong>Your Lichess account</strong> (its username and ID), when you sign in with Lichess: to give you a Chess Castles account. We never see your Lichess password. With your permission Lichess also lets Chess Castles play games, send challenges and join tournaments for you.</li>
    <li><strong>Profile details you choose to add</strong>: display name, first and last name, country, location, language, time zone, FIDE ID, status, "about me" and photo. Your photo is kept in Chess Castles' own database and shown only to you and your friends. We do not show photos from FIDE.</li>
    <li><strong>Friends and messages</strong>: who you are friends with, and messages between friends.</li>
    <li><strong>Games and progress</strong>: games you finish against Chess Castles' opponents (so you and your friends can review them), your CC Ratings, Vision Gym results, study points for the week and book chapters read (for the leaderboards).</li>
    <li><strong>Fair-play signals</strong>: in rated games, how often you leave the game's tab during your turn, and how you play, to keep games fair (see the <a href="/legal/fair-play">Fair play policy</a>).</li>
    <li><strong>Reports, support messages and feedback</strong> you send us. Feedback sent without signing in is anonymous; signed in, it is linked to your account so we can follow up if you allow it.</li>
    <li><strong>Your plan and what you use</strong>: your plan (Pawn, Bishop, Rook or Queen), how it was given (launch offer, invite, coach), and how many times a day you use features with limits, to apply them. Who invited you, if you joined with an invite link.</li>
    <li><strong>Coach tools</strong>: if you join a coach, the link between you and the work they set you. Your coach sees your ratings, your games on Chess Castles and your study this week, until you leave.</li>
    <li><strong>Anonymous usage counts</strong>: which pages are opened and features used, the kind of device, the country (from the connection, not stored with you) and the site a visit came from, counted per day. A random id in your browser lets us count visitors once a day; it is not linked to your account, no cookies are used, and nothing is sent when your browser asks not to be tracked.</li>
    <li><strong>Reminders</strong>: if you turn on study reminders, a push-notification address for your browser.</li>
    <li><strong>On your device only</strong>: settings, games played while signed out, your study plan and reading progress are kept in your browser's storage and are not sent to us unless stated above.</li>
  </ul>
  <p>We do not collect payment details, we do not use advertising or tracking cookies, and we do not sell or rent personal data.</p>

  <h2>3. Who can see what</h2>
  <ul>
    <li><strong>Anyone signed in</strong>: your display name, Lichess username, country, status and ratings, your place on leaderboards, and the game you are playing right now on Chess Castles (to watch it, as on Lichess; not players you have blocked).</li>
    <li><strong>Your friends only</strong> (both of you said yes): your photo, real name, location, "about me", your messages to them, and your finished Chess Castles games.</li>
    <li><strong>Chess Castles' team</strong>: what is needed to run the service, answer support messages and review reports.</li>
    <li><strong>Our service providers</strong>, who process data for us under their own security and privacy terms: Cloudflare (hosting and database) and Google Firebase (sign-in and profile). Data may be stored or processed outside India.</li>
    <li><strong>Lichess and chess.com</strong> receive only what you ask Chess Castles to send them (for example, your moves in a Lichess game). Their own privacy policies apply there.</li>
    <li>We may share data if the law requires it, or to protect players' safety.</li>
  </ul>

  <h2>4. Children</h2>
  <p>
    Many Chess Castles players are children. A child under 18 may use Chess Castles only with the consent of a parent or legal
    guardian. We do not show advertising, we do not track children's behaviour for advertising, messaging and photos are
    limited to friends who both agreed, and any player can be blocked and reported. A parent or guardian can ask to see,
    correct or delete their child's data through <a href="/help">Help &amp; support</a>.
  </p>

  <h2>5. How long we keep data</h2>
  <ul>
    <li>Your profile, friends and messages: while your account exists.</li>
    <li>Finished games shared with friends: the newest 100. A game in progress: until 30 minutes after it ends.</li>
    <li>Reports and support messages: as long as needed to deal with them and to keep the community safe. Feedback: up to two years, to see how Chess Castles improves.</li>
    <li>When you delete your account, we delete your profile, friends, messages and games within 30 days, except what the law requires us to keep.</li>
  </ul>

  <h2>6. Your rights</h2>
  <p>Under the DPDP Act you can:</p>
  <ul>
    <li>ask what personal data we hold about you and how it is used;</li>
    <li>correct or update it (most of it you can change yourself on your <a href="/profile">profile</a>);</li>
    <li>ask us to delete it, and withdraw consent at any time (this may end your account);</li>
    <li>name someone to use these rights for you if you cannot;</li>
    <li>complain to our grievance contact, and then to the Data Protection Board of India.</li>
  </ul>
  <p>To use any of these rights, write to us from <a href="/help">Help &amp; support</a> (choose "My account or data") or at <a href="mailto:support@chesscastles.com">support@chesscastles.com</a>.</p>
  <p>
    Our grievance contact is the Grievance Officer, Chess Castles, at <a href="mailto:support@chesscastles.com">support@chesscastles.com</a>
    (subject “Grievance”). We acknowledge complaints within 48 hours and aim to resolve them within one month.
  </p>

  <h2>7. Security</h2>
  <p>
    Data is sent over encrypted connections, sign-in uses Lichess and Firebase so we never handle passwords, and access to
    our systems is limited. No system is perfectly secure; if a breach affects you, we will tell you and the authorities as
    the law requires.
  </p>

