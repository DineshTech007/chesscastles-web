<LegalPage title="Fair play policy" updated="16 October 2026">
  <p class="box">
    Chess is only fun when everyone plays fair. Use your own head during games: no engines, no help from others, one
    account. Report anything that looks wrong; a person reviews it before any serious action.
  </p>

  <h2>1. What is not allowed</h2>
  <ul>
    <li><strong>Getting help during a game</strong>: chess engines, analysis boards or apps, another person's advice, or move databases, while the game is going on. This includes games against Chess Castles' FIDE-level opponents, tournaments and online games.</li>
    <li><strong>Losing on purpose</strong> (sandbagging) to lower a rating, or <strong>boosting</strong>: winning or losing games arranged with another player or account.</li>
    <li><strong>More than one account</strong>, or letting someone else play on your account.</li>
    <li><strong>Abuse</strong>: insulting, threatening or harassing players, or offensive names, photos or profile text.</li>
    <li><strong>False reports</strong> made on purpose to harm another player.</li>
  </ul>
  <p>
    Allowed: analysing your games after they end, reading books, using Chess Castles' lessons, puzzles and coach between
    games, and getting help from a coach outside your games.
  </p>

  <h2>2. How we keep games fair</h2>
  <ul>
    <li><strong>Game analysis</strong>: rated games can be checked for play far above a player's usual strength, unusual accuracy, and move times that do not look human, similar to how Lichess and chess.com work.</li>
    <li><strong>Leaving the game</strong>: like Lichess, Chess Castles notes how often a player switches away from the game's tab during their own turn. One switch means nothing; a pattern, together with other signs, may be reviewed.</li>
    <li><strong>Reports from players</strong>: every report is read.</li>
    <li><strong>Games on Lichess</strong> are also protected by Lichess's own fair-play team; their decisions apply to your Lichess account.</li>
  </ul>
  <p>Signals are never used alone: a strong action follows a review by a person.</p>

  <h2>3. What can happen</h2>
  <ul>
    <li>a warning;</li>
    <li>games removed from your CC Rating, tournament results and trophies taken back, or removal from leaderboards;</li>
    <li>limits on messaging or friends;</li>
    <li>suspending or closing the account.</li>
  </ul>
  <p>
    If action is taken on your account and you think it is a mistake, write to us from <a href="/help">Help &amp; support</a>
    and a different person on our team will look again.
  </p>

  <h2>4. How to report</h2>
  <p>
    Open the player's profile and choose <strong>Report</strong>. Pick what happened, add the game link if you have it,
    and send. Reports are private: the player is not told who reported them. You can also <strong>block</strong> a player,
    so they can no longer find or message you.
  </p>
  <p>If someone makes you feel unsafe, especially a child, block them, report them, and tell a parent, guardian or teacher.</p>
</LegalPage>
